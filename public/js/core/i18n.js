    // Load the language from the cookie or localStorage
    loadLanguage() {
        // First, try to read from the cookie (priority)
        const cookieLang = this.getCookie('lang');
        if (cookieLang && this.translations[cookieLang]) {
            this.currentLanguage = cookieLang;
        } else {
            // Sinon, essayer localStorage
            const storedLang = localStorage.getItem('lang');
            if (storedLang && this.translations[storedLang]) {
                this.currentLanguage = storedLang;
            }
        }
        
        // Update the HTML lang attribute
        document.documentElement.lang = this.currentLanguage;
    }
    
    // Get a cookie
    getCookie(name) {
        const value = `; ${document.cookie}`;
        const parts = value.split(`; ${name}=`);
        if (parts.length === 2) return parts.pop().split(';').shift();
        return null;
    }
    
    // Set the language
    setLanguage(lang) {
        if (!this.translations[lang]) {
            console.warn(`Language ${lang} not supported`);
            return;
        }
        
        this.currentLanguage = lang;
        document.documentElement.lang = lang;
        
        // Save to localStorage
        localStorage.setItem('lang', lang);
        
        // Set a cookie (will be synchronized with the server)
        document.cookie = `lang=${lang}; path=/; max-age=31536000`; // 1 an
        
        // Trigger an event to update the interface
        window.dispatchEvent(new CustomEvent('languageChanged', { detail: { lang } }));
    }
    
    // Traduire une clé
    t(key, params = {}) {
        const translation = this.translations[this.currentLanguage]?.[key] || 
                          this.translations['fr']?.[key] || 
                          key;
        
        // If the translation is not a string, return the key
        if (typeof translation !== 'string') {
            console.warn(`[i18n] The translation for "${key}" is not a string:`, translation);
       
            return key;
        }
        
        // Replace {param} parameters
        return translation.replace(/\{(\w+)\}/g, (match, param) => {
            return params[param] !== undefined ? params[param] : match;
        });
    }
    
    // Get the current language
    getCurrentLanguage() {
        return this.currentLanguage;
    }
    
    // Get all available languages
    getAvailableLanguages() {
        return Object.keys(this.translations);
    }
