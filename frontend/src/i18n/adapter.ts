function interpolate(template: string, params: Record<string, string | number>): string {
    return template.replace(/\{(\w+)\}/g, (match, name: string) => {
        const value = params[name];
        return value === undefined ? match : String(value);
    });
}

export function isSupportedLanguage(value: string): value is SupportedLanguage {
    return (SUPPORTED_LANGUAGES as readonly string[]).includes(value);
}

export function resolveLanguage(raw: string | undefined): SupportedLanguage {
    if (raw && isSupportedLanguage(raw)) {
        return raw;
    }
    return 'fr';
}

export function shellCatalog(language: 'fr' | 'en'): Readonly<Record<string, string>> {
    return SHELL_STRINGS[language];
}

/**
 * Translate a shell key. Prefers the legacy i18n.js dictionary when the key
 * exists there (ADR-08), then the FR/EN shell catalogue, then the key itself.
 */
export function translate(
    key: string,
    params: Record<string, string | number> = {},
    language?: string,
): string {
    const lang = resolveLanguage(language ?? window.i18n?.getCurrentLanguage());
    const fromLegacy = window.i18n?.t(key, params);
    if (fromLegacy && fromLegacy !== key) {
        return fromLegacy;
    }
    const table = lang === 'en' ? SHELL_STRINGS.en : SHELL_STRINGS.fr;
    const template = table[key] ?? SHELL_STRINGS.fr[key] ?? key;
    return interpolate(template, params);
}

export function setShellLanguage(lang: string): boolean {
    if (typeof window.setLanguage === 'function') {
        return window.setLanguage(lang) === true;
    }
    if (window.i18n && isSupportedLanguage(lang)) {
        window.i18n.setLanguage(lang);
        return true;
    }
    return false;
}
